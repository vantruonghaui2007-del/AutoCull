#!/usr/bin/env node
// Lists every npm package that ships inside the desktop app (production dependency tree plus the
// packages bundled into the renderer/main by Vite) with its declared license and whether a license
// file is present. Native/binary components are listed separately in docs/LICENSES.md because the
// wrapper's license does not describe the binaries inside it.
// Usage: node scripts/license-inventory.mjs  -> writes docs/license-inventory.json and .md
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { cwd: root, encoding: 'utf8', shell: true, maxBuffer: 64 * 1024 * 1024 }));
const seen = new Map();
const walk = (deps, via) => {
  for (const [name, d] of Object.entries(deps ?? {})) {
    const key = `${name}@${d.version}`;
    // Optional packages for another OS (e.g. exiftool-vendored.pl on Windows) have no path here.
    if (!seen.has(key) && d.path && existsSync(d.path)) seen.set(key, { name, version: d.version, path: d.path, via });
    walk(d.dependencies, via);
  }
};
walk(tree.dependencies, 'dependency');
// Bundled into out/renderer by Vite (devDependencies at build time, shipped at run time).
for (const name of ['react', 'react-dom', 'scheduler']) {
  const p = path.join(root, 'node_modules', name);
  const v = JSON.parse(readFileSync(path.join(p, 'package.json'), 'utf8')).version;
  seen.set(`${name}@${v}`, { name, version: v, path: p, via: 'bundled-in-renderer' });
}
const ep = path.join(root, 'node_modules', 'electron');
seen.set(`electron@${JSON.parse(readFileSync(path.join(ep, 'package.json'), 'utf8')).version}`, {
  name: 'electron',
  version: JSON.parse(readFileSync(path.join(ep, 'package.json'), 'utf8')).version,
  path: ep,
  via: 'runtime (Chromium + Node.js; see LICENSES.chromium.html in the app folder)',
});

const rows = [...seen.values()]
  .map((r) => {
    const pkg = JSON.parse(readFileSync(path.join(r.path, 'package.json'), 'utf8'));
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
    const files = existsSync(r.path) ? readdirSync(r.path).filter((f) => /^(licen[cs]e|copying|notice)/i.test(f)) : [];
    return { ...r, license: license || 'UNKNOWN', licenseFiles: files, path: path.relative(root, r.path).replaceAll('\\', '/') };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

writeFileSync(path.join(root, 'docs', 'license-inventory.json'), `${JSON.stringify(rows, null, 2)}\n`);
const md = [
  '# npm packages shipped in the desktop app (generated)',
  '',
  'Generated by `node scripts/license-inventory.mjs`. Native binaries inside these packages are audited separately in `docs/LICENSES.md`.',
  '',
  '| Package | Version | Declared license | License file | How it ships |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.licenseFiles.join(', ') || '**none found**'} | ${r.via} |`),
  '',
];
writeFileSync(path.join(root, 'docs', 'license-inventory.md'), md.join('\n'));
const unknown = rows.filter((r) => r.license === 'UNKNOWN' || r.licenseFiles.length === 0);
console.log(`${rows.length} packages; ${unknown.length} without a declared license or license file`);
for (const u of unknown) console.log(`  check: ${u.name}@${u.version} (${u.license}, files: ${u.licenseFiles.join(',') || 'none'})`);
